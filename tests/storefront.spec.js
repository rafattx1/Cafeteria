import { test, expect } from '@playwright/test';
test('sacola, cupom, entrega e confirmação de Pix demonstrativo',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Adicionar Cappuccino Italiano à sacola'}).click();
 await page.getByRole('button',{name:'Adicionar Croissant de Amêndoas à sacola'}).click();
 await page.getByRole('button',{name:'Sacola',exact:false}).first().click();
 const dialog=page.getByRole('dialog');
 await expect(dialog.locator('.grand-total')).toContainText('R$ 36,80');
 await dialog.getByRole('textbox',{name:'Cupom de desconto'}).fill('PRIMEIRAPAUSA');
 await dialog.getByRole('button',{name:'Aplicar',exact:true}).click();
 await dialog.getByRole('button',{name:'Entrega · R$ 6,00'}).click();
 await expect(dialog.locator('.grand-total')).toContainText('R$ 40,96');
 await dialog.getByRole('button',{name:'Continuar para pagamento'}).click();
 await dialog.getByRole('textbox',{name:'Nome',exact:true}).fill('Cliente Teste');
 await dialog.getByRole('textbox',{name:'E-mail',exact:true}).fill('teste@example.com');
 await dialog.getByRole('textbox',{name:'Endereço de entrega demonstrativo'}).fill('Rua de teste, 123');
 await dialog.getByRole('button',{name:'Confirmar pagamento simulado'}).click();
 await expect(dialog.getByText('Nenhuma cobrança foi realizada.',{exact:true})).toBeVisible();
 await expect(dialog.locator('.success-details')).toContainText('R$ 40,96');
 await dialog.getByRole('button',{name:'Voltar para o cardápio'}).click();
 await expect(dialog).not.toBeVisible();
 await expect(page.locator('.cart-count')).toHaveText('0');
});
